@app.command("score")
def score_command(
    ticker: str | None = typer.Argument(
        None,
        help="Optional ticker filter, e.g. 601061.SH. Default: whole memory log.",
    ),
):
    """Print T+1 directional hit rate from the memory log. Research scorecard, not an order."""
    from tradingagents.agents.utils.hit_rate import (
        fetch_next_session_return,
        summarize_memory_log,
    )
    from tradingagents.agents.utils.memory import TradingMemoryLog

    log = TradingMemoryLog(DEFAULT_CONFIG)
    summary = summarize_memory_log(
        log, ticker=ticker, next_session_loader=fetch_next_session_return
    )
    if summary["total"] == 0:
        console.print("[yellow]Memory log is empty. Run predict/analyze first.[/yellow]")
        raise typer.Exit(code=0)

    def _rate(value: float | None) -> str:
        return "n/a" if value is None else f"{value:.0%}"

    def _mean(value: float | None) -> str:
        return "n/a" if value is None else f"{value:+.1%}"

    console.print(
        "[bold cyan]Prediction scorecard[/bold cyan] — T+1 (as-of close → next "
        "session) is primary; 5-day settled raw is secondary. BUY/SELL only; "
        "Hold stays out. Never a broker order.\n"
    )
    if ticker:
        console.print(f"Ticker: {ticker}")
    console.print(
        f"Entries: {summary['total']}  pending: {summary['pending']}  "
        f"resolved: {summary['resolved']}"
    )
    console.print(
        f"T+1 hits: {summary['t1_hits']}  hit rate: {_rate(summary['t1_hit_rate'])}  "
        f"mean raw: {_mean(summary['t1_mean_raw'])}  "
        f"directional: {summary['t1_directional']}"
    )
    console.print(
        f"5d settled hits: {summary['hold_5d_hits']}  "
        f"hit rate: {_rate(summary['hold_5d_hit_rate'])}  "
        f"mean raw: {_mean(summary['hold_5d_mean_raw'])}  "
        f"directional: {summary['hold_5d_directional']}"
    )
    by_rating = summary.get("t1_by_rating") or {}
    if by_rating:
        parts = []
        for label, bucket in by_rating.items():
            if bucket.get("directional"):
                parts.append(
                    f"{label} {_rate(bucket.get('hit_rate'))} "
                    f"(n={bucket['directional']})"
                )
        if parts:
            console.print("T+1 by rating: " + "  ".join(parts))
    table = Table(box=box.SIMPLE, show_header=True)
    table.add_column("Date")
    table.add_column("Ticker")
    table.add_column("Rating")
    table.add_column("T+1")
    table.add_column("5d raw")
    table.add_column("Status")
    for row in summary["entries"][-20:]:
        status = "pending" if row.get("pending") else "settled"
        t1_raw = row.get("t1_raw")
        t1_text = _mean(t1_raw) if isinstance(t1_raw, (int, float)) else "n/a"
        table.add_row(
            str(row.get("date") or ""),
            str(row.get("ticker") or ""),
            str(row.get("rating") or ""),
            t1_text,
            str(row.get("raw") or ""),
            status,
        )
    console.print(table)


